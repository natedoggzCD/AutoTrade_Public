_manager: Optional[DataSyncManager] = None


def get_manager() -> DataSyncManager:
    """Get or create singleton DataSyncManager instance."""
    global _manager
    if _manager is None:
        _manager = DataSyncManager()
    return _manager


def check_sync() -> Dict[str, Any]:
    """Check sync status for all data sources."""
    return get_manager().check_sync_status()


