if __name__ == "__main__":
    import sys

    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s | %(levelname)s | %(message)s"
    )

    manager = DataSyncManager()

    if len(sys.argv) > 1:
        command = sys.argv[1].lower()

        if command == "check":
            status = manager.check_sync_status()
            print(f"\n{'=' * 50}")
            print("Data Sync Status")
            print(f"{'=' * 50}")
            print(f"Primary Date: {status.get('primary_date')}")
            print(f"Tickers: {status.get('primary_tickers')}")
            print(f"All Synced: {status.get('all_synced')}")
            print("\nSources:")
            for name, info in status.get("sources", {}).items():
                sync_icon = "[OK]" if info.get("is_current") else "[!!]"
                print(f"  {sync_icon} {name}: {info.get('latest_date', 'N/A')}")

        elif command == "sync":
            results = manager.sync_all()
            print("\nSync Results:")
            for source, success in results.items():
                icon = "[OK]" if success else "[FAIL]"
                print(f"  {icon} {source}")

        elif command == "rebuild":
            print("Rebuilding DuckDB views...")
            success = manager.sync_duckdb(force=True)
            print(f"Rebuild: {'OK' if success else 'FAILED'}")

        else:
            print(f"Unknown command: {command}")
            print("Usage: python data_sync.py [check|sync|rebuild]")
    else:
        # Default: check and sync if needed
        freshness = manager.get_data_freshness()
        print(f"\nData Freshness: {freshness['status']}")
        print(f"  {freshness['message']}")

        if not freshness.get("all_synced"):
            print("\nSyncing...")
            manager.sync_all()
