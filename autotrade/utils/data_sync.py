"""
Data Sync Utility - Ensures all data sources are synchronized.

Verifies that:
1. DuckDB matches the latest date in daily_features.parquet
2. All local data files are current (updated today)
3. Rebuilds DuckDB views if out of sync

Run modes:
- check: Just verify sync status
- sync: Verify and fix any issues
- rebuild: Force rebuild all DuckDB views

Usage:
    from autotrade.utils.data_sync import DataSyncManager
    sync = DataSyncManager()
    status = sync.check_sync_status()
    if not status['all_synced']:
        sync.sync_all()
"""

